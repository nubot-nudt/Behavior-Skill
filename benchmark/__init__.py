"""
Behavior-Skill: standalone per-skill evaluation package.

Architecture (compared with full-task evaluation)
─────────────────────────────────────────────────────────────────────────────

Full-task evaluation:
  goal:       problem0.bddl (:goal block)
  init state: tro_state.json → load_task_instance() = og.sim.load_state()

Per-skill evaluation:
  goal:       skill_eval_configs/{task}.yaml (bddl_goal field per skill),
              using or/forall to handle multiple objects
  init state: skill_init_states/state_manifest.json → skill_N.npz
              = compressed og.sim.dump_state(serialized=True)

Key mechanisms:
  1. predefined_problem injects the skill-specific BDDL (objects + init + skill_goal);
     BehaviorTask initializes PredicateGoal with skill_goal
  2. after env.reset(), og.sim.load_state(state_vec, serialized=True) overwrites
     the BDDL :init physical state with the training-trajectory checkpoint state
  3. env.step()'s info["done"]["success"] checks skill_goal (same pipeline as the full task)

Notes:
  - skill_eval_configs/*.yaml are manually authored; no frame_range / HDF5 paths
  - state_manifest.json is generated by an offline state-extraction pipeline
    (not part of this repo)
  - evaluation never touches training-annotation JSONs (fully decoupled)

Module layout
─────────────────────────────────────────────────────────────────────────────
  skill_eval.py    CLI entry point (main / argparse), the only entry
  core/            evaluation core
      evaluator.py     SkillEvaluator (per-skill evaluator) + run_batch
      suite.py         eval_config YAML / state_manifest.json loading + prompt override table
      skill_bddl.py    BDDL building, parsing and scene wildcard expansion
      observation.py   policy observation preprocessing + eval env config generation
  states/          skill start-state loading (loader) and restore fixes (restore_fixes)
  policies/        policy backends: remote websocket service / local hydra instantiation
  utils/           output helpers: video recording (video), diagnostic logging (diagnostics)
  scripts/         batch-evaluation shell scripts
"""

